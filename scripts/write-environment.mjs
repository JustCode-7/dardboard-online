// Generates src/environments/environment.ts for production builds (GitHub Pages workflow).
//
// Values come from GitHub repository Variables (Settings -> Secrets and variables -> Actions -> Variables),
// passed in as environment variables. The Firebase web config is public by design; access is enforced by
// Firebase Auth, firestore.rules and the authoritative backend. Never put service-account keys here.
//
// Usage: FIREBASE_API_KEY=... FIREBASE_AUTH_DOMAIN=... FIREBASE_PROJECT_ID=... FIREBASE_APP_ID=... \
//        CALLABLE_BASE_URL=https://<project-id>.web.app/api [FIREBASE_DATABASE_ID=...] \
//        node scripts/write-environment.mjs
//
// FIREBASE_DATABASE_ID is optional; set it when using a named Firestore database (not '(default)').
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const REQUIRED = ['FIREBASE_API_KEY', 'FIREBASE_AUTH_DOMAIN', 'FIREBASE_PROJECT_ID', 'FIREBASE_APP_ID', 'CALLABLE_BASE_URL'];

const missing = REQUIRED.filter(name => !process.env[name]?.trim());
if (missing.length > 0) {
  console.error(`Missing repository variables: ${missing.join(', ')}`);
  console.error('Set them under Settings -> Secrets and variables -> Actions -> Variables (see README, "GitHub Pages").');
  process.exit(1);
}

const value = name => process.env[name]?.trim();
const callableBaseUrl = value('CALLABLE_BASE_URL').replace(/\/+$/, '');
if (!/^https:\/\//.test(callableBaseUrl)) {
  console.error('CALLABLE_BASE_URL must be an https:// URL, e.g. https://<project-id>.web.app/api');
  process.exit(1);
}

const firebaseConfig = {
  apiKey: value('FIREBASE_API_KEY'),
  authDomain: value('FIREBASE_AUTH_DOMAIN'),
  projectId: value('FIREBASE_PROJECT_ID'),
  appId: value('FIREBASE_APP_ID'),
};

// Optional: named Firestore database (defaults to '(default)' if not set)
const databaseId = value('FIREBASE_DATABASE_ID');
if (databaseId) {
  firebaseConfig.databaseId = databaseId;
}

const environment = {
  production: true,
  firebase: firebaseConfig,
  emulators: null,
  callableBaseUrl,
};

const target = resolve(dirname(fileURLToPath(import.meta.url)), '../src/environments/environment.ts');
const source = `// Generated by scripts/write-environment.mjs - do not edit in CI builds.
import { AppEnvironment } from './app-environment';

export const environment: AppEnvironment = ${JSON.stringify(environment, null, 2)};
`;
writeFileSync(target, source, 'utf8');
console.log(`Wrote ${target} (project ${environment.firebase.projectId}, callables ${callableBaseUrl})`);
